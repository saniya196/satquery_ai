const DICTS: Record<UiLanguage, Dict> = { en, hi, te }

interface LanguageContextValue {
  lang: UiLanguage
  setLang: (lang: UiLanguage) => void
  t: (key: string, fallback?: string) => string
  querySupported: boolean
  speechLang: string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<UiLanguage>(() => {
    const stored = localStorage.getItem(STORAGE_KEY)
    return stored === 'hi' || stored === 'te' || stored === 'en' ? stored : 'en'
  })

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, lang)
    document.documentElement.lang = lang
  }, [lang])

  const value = useMemo<LanguageContextValue>(() => ({
    lang,
    setLang: setLangState,
    t: (key: string, fallback?: string) => DICTS[lang][key] ?? en[key] ?? fallback ?? key,
    querySupported: QUERY_LANGUAGE_SUPPORT[lang] === 'supported',
    speechLang: lang === 'hi' ? 'hi-IN' : lang === 'te' ? 'te-IN' : 'en-IN',
  }), [lang])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const ctx = useContext(LanguageContext)
  if (!ctx) throw new Error('useLanguage must be used within LanguageProvider')
  return ctx
}
